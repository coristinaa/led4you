// Builds html_studio.h: inlines studio.js into studio.htm, gzips it and writes a C array.
// Run from the repository root: node usermods/led4you_ble/studio/build_studio.js
const fs = require('fs'), path = require('path'), zlib = require('zlib');
const dir = __dirname;
let html = fs.readFileSync(path.join(dir, 'studio.htm'), 'utf8');
const js = fs.readFileSync(path.join(dir, 'studio.js'), 'utf8');
html = html.replace('<script src="studio.js"></script>', () => '<script>' + js + '</script>');
const gz = zlib.gzipSync(Buffer.from(html, 'utf8'), { level: 9 });
let out = '// Generated by studio/build_studio.js - do not edit\n#pragma once\n';
out += 'const uint16_t PAGE_studio_length = ' + gz.length + ';\n';
out += 'const uint8_t PAGE_studio[] PROGMEM = {\n';
for (let i = 0; i < gz.length; i += 20) out += '  ' + Array.from(gz.slice(i, i + 20)).map(b => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',\n';
out += '};\n';
fs.writeFileSync(path.join(dir, '..', 'html_studio.h'), out);
console.log('html_studio.h: ' + html.length + ' bytes -> ' + gz.length + ' gzipped');
