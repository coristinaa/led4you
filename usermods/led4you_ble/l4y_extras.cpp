/*
 * LED4YOU Extras usermod
 *  - seasonal effects: Candy Cane, Snowfall, Haunted, Retro Tree
 *  - schedule: switch on at a time or at sunset (optionally with a preset), switch off at a time or at sunrise
 *  - time and location from the app ({"time":unix} is WLED's own API, {"l4y":{"tz":sec,"geo":[lat,lon]}})
 *  - countdown shown by the Scrolling Text effect ({"l4y":{"cd":{"on":1,"t":localUnix,"n":"XMAS"}}})
 *  - motion sensor (PIR) that plays a preset for a few seconds, then restores what was showing
 *  - group sync switches (WLED UDP notifications) and playlist stop
 *  - house scenes: one command plays preset N on every LED4YOU in the house (UDP broadcast, each board its own preset N)
 * Everything is set through the JSON state API under "l4y", so the app (Bluetooth) and the
 * Studio page (Wi-Fi) use the same commands. Status is reported in /json/state "l4y" and over Bluetooth.
 */
