// LED4YOU: DMX output is switched on and its pin chosen in Config > Usermods > LED4YOU Extras (applied at boot)
bool l4yDmxOutOn = false;
int8_t l4yDmxOutPin = -1;
uint16_t l4yDmxOutFixtures = 0;   // how many fixtures follow the LEDs (0 = as many as fit in the 512 channels)
static bool l4yDmxOutStarted = false;
// LED4YOU: "music" mode, the DMX lights follow the sound (AudioReactive: INMP441 or the phone's microphone) instead of
// the LEDs. 0 = follow the LEDs, 1 = pulse with the volume, 2 = new colour on each beat, 3 = bass / mids / treble
// (one band per light), 4 = strobe on the beat. Sensitivity 0..255. Changed live from the app, kept in the config.
uint8_t l4yDmxMusic = 0;   // 5 = each light does its own thing (l4yDmxLight)
uint8_t l4yDmxSens = 128;
// what each light does in mode 5: f = L4Y_DMXF_..., v = LED number (follow an LED) or colour 0xRRGGBB (0 = usual colour)
L4yDmxLight l4yDmxLight[L4Y_DMX_LIGHTS];

// AI: below section was generated by an AI
// writes one fixture: colour r g b w at a level 0..255 (dimmer channel when the fixture has one, otherwise scaled colour)
static void l4yDmxFixture(int start, uint8_t r, uint8_t g, uint8_t b, uint8_t w, uint8_t level, uint8_t brightness, bool hasShutter) {
  const unsigned lv = hasShutter ? 255 : (unsigned)level * brightness / 255;
  for (int j = 0; j < DMXChannels && j < 15; j++) {
    const int addr = start + j;
    if (addr > 512) break;
    switch (DMXFixtureMap[j]) {
      case 0: dmx.write(addr, 0); break;
      case 1: dmx.write(addr, r * lv / 255); break;
      case 2: dmx.write(addr, g * lv / 255); break;
      case 3: dmx.write(addr, b * lv / 255); break;
      case 4: dmx.write(addr, w * lv / 255); break;
      case 5: dmx.write(addr, (unsigned)level * brightness / 255); break;
      case 6: dmx.write(addr, 255); break;
    }
  }
}

// follows one sound value and turns it into 0..255 relative to how loud it has been lately, so a light really moves with
// the music instead of sitting near full (the band values stay high all through a loud song)
struct L4yEnv {
  float avg = 0, pk = 1, out = 0;
  uint8_t level(float e, float sens) {               // sens 0..1: higher = reacts to smaller changes
    avg = avg * 0.97f + e * 0.03f;                   // about 1 s average
    pk = max(e, pk * 0.996f);                        // recent loudest, falls slowly
    if (pk < avg + 10) pk = avg + 10;
    const float floorV = avg * (1.05f - 0.55f * sens);
    float x = e < 3 ? 0 : (e - floorV) / (pk - floorV);
    x = x < 0 ? 0 : x > 1 ? 1 : x;
    x *= x;                                          // more contrast: quiet parts dark, hits bright
    out = max(x, out * 0.80f);                       // jumps up at once, fades in about 0.1 s
    return (uint8_t)(out * 255);
  }
};

static void l4yDmxMusicFrame(uint8_t brightness, bool hasShutter) {
  static float avgBass = 0, flash = 0, flashS = 0, hueF = 0;
  static L4yEnv eVol, eBass, eMid, eTre;
  static uint8_t strobeHue = 0;
  static uint32_t lastBeat = 0;
  static uint16_t beats = 0;
  static bool lastPeak = false;
  um_data_t* um = nullptr;
  const bool have = UsermodManager::getUMData(&um, USERMOD_ID_AUDIOREACTIVE) && um;
  const float vol = have ? *(float*)um->u_data[0] : 0.0f;              // smoothed volume 0..255
  const uint8_t* fft = have ? (const uint8_t*)um->u_data[2] : nullptr;  // 16 frequency bands 0..255
  const bool peak = have && *(uint8_t*)um->u_data[3];
  float bass = 0, mid = 0, tre = 0;
  if (fft) {
    for (int i = 0; i < 4; i++) bass += fft[i];
    for (int i = 4; i < 10; i++) mid += fft[i];
    for (int i = 10; i < 16; i++) tre += fft[i];
    bass /= 4; mid /= 6; tre /= 6;
  }
  const float thr  = 1.7f - l4yDmxSens / 400.0f;          // a beat is bass this much above its average (1.7 .. 1.06)
  avgBass = avgBass * 0.93f + bass * 0.07f;
  const uint32_t now = millis();
  const bool beat = now - lastBeat > 180 && ((bass > avgBass * thr && bass > 24) || (peak && !lastPeak));
  lastPeak = peak;
  if (beat) { lastBeat = now; beats++; flash = flashS = 255; hueF += 37; strobeHue += 85 + (beats & 3) * 13; }
  flash *= 0.82f;                                         // colour on the beat: fades in about 0.2 s
  flashS *= 0.55f;                                        // strobe: short flash
  hueF += 0.4f;                                           // slow colour drift between beats
  const uint8_t hue = (uint8_t)((int)hueF & 0xFF);
  const float sn = l4yDmxSens / 255.0f;
  const uint8_t lvVol = eVol.level(vol, sn);
  const uint8_t lvBass = eBass.level(bass, sn), lvMid = eMid.level(mid, sn), lvTre = eTre.level(tre, sn);
  const int n = l4yDmxOutFixtures ? l4yDmxOutFixtures : 1;
  for (int k = 0; k < n; k++) {
    const int start = DMXStart + DMXGap * k;
    if (start > 512) break;
    // what this light does: its own choice (mode 5) or the one style for all
    uint8_t f; uint32_t v = 0;
    if (l4yDmxMusic == 5) {
      if (k < L4Y_DMX_LIGHTS) { f = l4yDmxLight[k].f; v = l4yDmxLight[k].v; }
      else { f = L4Y_DMXF_LED; v = DMXStartLED + k; }   // lights past the list follow the LEDs one after the other
    } else {
      f = l4yDmxMusic == 1 ? L4Y_DMXF_PULSE : l4yDmxMusic == 2 ? L4Y_DMXF_BEAT : l4yDmxMusic == 3 ? (uint8_t)(L4Y_DMXF_BASS + k % 3) : L4Y_DMXF_STROBE;
    }
    CRGB c; uint8_t level = 0, w = 0;
    const bool own = v != 0;                               // a colour chosen in the app (0 = the usual one)
    const CRGB oc((v >> 16) & 0xFF, (v >> 8) & 0xFF, v & 0xFF);
    switch (f) {
      case L4Y_DMXF_LED: {                                 // follow an LED: its colour as the lights show it
        const uint32_t in = v < strip.getLengthTotal() ? strip.getPixelColor(v) : 0;
        l4yDmxFixture(start, R(in), G(in), B(in), W(in), 255, brightness, hasShutter);
        continue;
      }
      case L4Y_DMXF_PULSE: c = own ? oc : (CRGB)CHSV(hue + k * 24, 255, 255); level = lvVol; break;
      case L4Y_DMXF_BEAT:  c = CHSV(hue + k * (256 / (n > 1 ? n : 2)), 255, 255); level = max((int)flash, lvVol / 2); break;
      case L4Y_DMXF_BASS:  c = own ? oc : CRGB(255, 0, 0); level = lvBass; break;
      case L4Y_DMXF_MIDS:  c = own ? oc : CRGB(0, 255, 0); level = lvMid; break;
      case L4Y_DMXF_TREBLE:c = own ? oc : CRGB(0, 0, 255); level = lvTre; break;
      case L4Y_DMXF_STROBE:                                // a new colour on every flash (or the colour chosen in the app)
        c = own ? oc : (CRGB)CHSV(strobeHue + k * 40, 255, 255);
        level = ((beats + k) & 1) || n == 1 || l4yDmxMusic == 5 ? (uint8_t)flashS : (uint8_t)(flashS / 4); break;
      case L4Y_DMXF_STROBE1:                               // flash on the beat in one colour
        c = own ? oc : CRGB(255, 255, 255); w = own ? 0 : 255; level = (uint8_t)flashS; break;
      default:             c = oc; level = 255; break;    // fixed colour
    }
    l4yDmxFixture(start, c.r, c.g, c.b, w, level, brightness, hasShutter);
  }
  dmx.update();
}
